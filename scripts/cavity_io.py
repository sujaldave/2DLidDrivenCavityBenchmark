#!/usr/bin/env python3
"""Shared I/O and numerical utilities for the cavity benchmark."""

from __future__ import annotations

import csv
import json
import math
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable


RESULT_PATTERN = re.compile(r"result_(\d+)\.vtu$")


@dataclass(frozen=True)
class StructuredResult:
    path: Path
    step: int
    x: object
    y: object
    u: object
    v: object


def load_config(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def case_map(config: dict) -> dict[int, dict]:
    return {int(item["reynolds"]): item for item in config["cases"]}


def select_reynolds(config: dict, requested: Iterable[int] | None) -> list[int]:
    available = case_map(config)
    selected = sorted(available) if requested is None else list(dict.fromkeys(requested))
    unknown = sorted(set(selected) - set(available))
    if unknown:
        raise ValueError(f"No configured case for Reynolds number(s): {unknown}")
    return selected


def result_step(path: Path) -> int:
    match = RESULT_PATTERN.fullmatch(path.name)
    return int(match.group(1)) if match else -1


def latest_result(case_dir: Path) -> Path:
    candidates = [path for path in case_dir.rglob("result_*.vtu") if result_step(path) >= 0]
    if not candidates:
        raise FileNotFoundError(f"No result_*.vtu file found below {case_dir}")
    return max(candidates, key=lambda path: (result_step(path), path.stat().st_mtime_ns))


def read_structured_result(path: Path) -> StructuredResult:
    try:
        import numpy as np
        import vtk
        from vtk.util.numpy_support import vtk_to_numpy
    except ImportError as exc:
        raise RuntimeError(
            "Reading results requires numpy and vtk. Install requirements.txt first."
        ) from exc

    reader = vtk.vtkXMLUnstructuredGridReader()
    reader.SetFileName(str(path))
    reader.Update()
    grid = reader.GetOutput()
    if grid is None or grid.GetNumberOfPoints() == 0:
        raise RuntimeError(f"Could not read a nonempty unstructured grid from {path}")

    velocity_array = grid.GetPointData().GetArray("Velocity")
    if velocity_array is None or velocity_array.GetNumberOfComponents() < 2:
        names = [
            grid.GetPointData().GetArrayName(index)
            for index in range(grid.GetPointData().GetNumberOfArrays())
        ]
        raise RuntimeError(
            f"Point-data array 'Velocity' with at least two components is absent "
            f"from {path}; available arrays: {names}"
        )

    points = vtk_to_numpy(grid.GetPoints().GetData())[:, :2].astype(float)
    velocity = vtk_to_numpy(velocity_array)[:, :2].astype(float)
    x = np.unique(np.round(points[:, 0], 12))
    y = np.unique(np.round(points[:, 1], 12))
    if len(x) * len(y) != grid.GetNumberOfPoints():
        raise RuntimeError(
            f"{path} is not a complete Cartesian point grid; this benchmark "
            "expects the structured meshes generated by generate_cases.py"
        )

    x_index = {value: index for index, value in enumerate(x)}
    y_index = {value: index for index, value in enumerate(y)}
    u = np.full((len(y), len(x)), np.nan)
    v = np.full_like(u, np.nan)
    for (px, py), (up, vp) in zip(points, velocity):
        i = x_index[round(float(px), 12)]
        j = y_index[round(float(py), 12)]
        u[j, i] = up
        v[j, i] = vp
    if np.isnan(u).any() or np.isnan(v).any():
        raise RuntimeError(f"Could not map every result point in {path} to the grid")
    return StructuredResult(path=path, step=result_step(path), x=x, y=y, u=u, v=v)


def centerline_profiles(result: StructuredResult):
    """Return u(0.5,y) and v(x,0.5) from an odd-point Cartesian mesh."""
    import numpy as np

    i = int(np.argmin(np.abs(result.x - 0.5)))
    j = int(np.argmin(np.abs(result.y - 0.5)))
    tolerance = 1.0e-10
    if abs(float(result.x[i]) - 0.5) > tolerance or abs(float(result.y[j]) - 0.5) > tolerance:
        raise RuntimeError("The generated mesh must contain x=0.5 and y=0.5 centerlines")
    return result.y, result.u[:, i], result.x, result.v[j, :]


def reconstruct_streamfunction(result: StructuredResult):
    """Reconstruct psi using u=dpsi/dy and v=-dpsi/dx.

    Bottom-up and left-to-right trapezoidal integrations are averaged. A
    linear drift correction enforces psi=0 on each pair of opposite walls.
    """
    import numpy as np

    x, y, u, v = result.x, result.y, result.u, result.v
    from_bottom = np.zeros_like(u)
    from_bottom[1:, :] = np.cumsum(
        0.5 * (u[:-1, :] + u[1:, :]) * np.diff(y)[:, None], axis=0
    )
    from_bottom -= ((y - y[0]) / (y[-1] - y[0]))[:, None] * from_bottom[-1:, :]

    from_left = np.zeros_like(v)
    from_left[:, 1:] = np.cumsum(
        -0.5 * (v[:, :-1] + v[:, 1:]) * np.diff(x)[None, :], axis=1
    )
    from_left -= from_left[:, -1:] * ((x - x[0]) / (x[-1] - x[0]))[None, :]
    return 0.5 * (from_bottom + from_left)


def primary_vortex_center(result: StructuredResult) -> tuple[float, float, float]:
    """Locate the clockwise primary vortex at the interior minimum of psi."""
    import numpy as np

    psi = reconstruct_streamfunction(result)
    interior = psi[1:-1, 1:-1]
    j_local, i_local = np.unravel_index(int(np.argmin(interior)), interior.shape)
    j, i = j_local + 1, i_local + 1
    return float(result.x[i]), float(result.y[j]), float(psi[j, i])


def read_reference_profile(path: Path, coordinate_name: str, reynolds: int):
    import numpy as np

    coordinates: list[float] = []
    values: list[float] = []
    column = f"Re{reynolds}"
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames is None or coordinate_name not in reader.fieldnames or column not in reader.fieldnames:
            raise ValueError(f"{path} does not contain columns {coordinate_name!r} and {column!r}")
        for row in reader:
            coordinates.append(float(row[coordinate_name]))
            values.append(float(row[column]))
    return np.asarray(coordinates), np.asarray(values)


def read_primary_vortex_references(path: Path) -> dict[int, tuple[float, float]]:
    references: dict[int, tuple[float, float]] = {}
    with path.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            if row["vortex"] == "Primary":
                references[int(row["reynolds"])] = (float(row["x"]), float(row["y"]))
    return references


def error_metrics(reference, computed) -> dict[str, float]:
    import numpy as np

    difference = np.asarray(computed) - np.asarray(reference)
    reference = np.asarray(reference)
    absolute_l2 = float(np.linalg.norm(difference))
    reference_l2 = float(np.linalg.norm(reference))
    return {
        "absolute_l2": absolute_l2,
        "relative_l2": absolute_l2 / reference_l2 if reference_l2 else math.nan,
        "rmse": float(np.sqrt(np.mean(difference**2))),
        "max_abs_error": float(np.max(np.abs(difference))),
    }


def write_csv(path: Path, rows: list[dict], fieldnames: list[str] | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows and not fieldnames:
        raise ValueError(f"Cannot infer columns for empty CSV: {path}")
    columns = fieldnames or list(rows[0])
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)
